"""Быстрые ответы без нейросети: просьбы, смысл которых ясен по словам («который час», «громче», «сверни окна»).

Такая просьба выполняется сразу (десятые доли секунды) и не зависит ни от сети, ни от модели. Всё, что не подошло под
правила, идёт в нейросеть. Правила намеренно узкие: лучше отдать фразу модели, чем сделать не то."""
from __future__ import annotations

import re
from typing import List, Optional, Tuple

from .core import normalize

# Названия программ, которые jarvis-pc открывает без угадывания (сверяется с pc.py тестом)
APPS = ["блокнот", "калькулятор", "проводник", "диспетчер задач", "пейнт", "командная строка", "терминал", "настройки",
        "параметры", "панель управления", "браузер", "ютуб", "хром", "эдж", "фаерфокс", "телеграм", "стим", "дискорд"]

_FILLER = r"(?:пожалуиста|будь добр|быстро|мне|для меня)"          # уже в виде после normalize(): й -> и


def _rules() -> List[Tuple[re.Pattern, object]]:
    def rx(pattern: str) -> re.Pattern:
        # normalize() заменяет й на и и ё на е: шаблоны приводятся к тому же виду
        return re.compile(pattern.replace("й", "и").replace("ё", "е"))
    return [
        (rx(r"^(?:скажи )?(?:который час|сколько (?:сейчас )?времени|какое (?:сегодня )?число|какой (?:сегодня )?день|"
            r"какая (?:сегодня )?дата|время|дата)$"), ["now"]),
        (rx(r"^(?:какая )?(?:сейчас )?погода(?: сейчас| на улице| сегодня| за окном)?$"), ["weather"]),
        (rx(r"^(?:какой )?курс (доллара|евро|юаня|фунта|тенге|гривны|лиры|иены)(?: сегодня| сейчас)?$"), lambda m: ["rate", m.group(1)]),
        (rx(r"^(?:сверни|свернуть) (?:все )?окна$|^покажи рабочий стол$"), ["minimize-all"]),
        (rx(r"^(?:верни|вернуть|разверни|показать) (?:все )?окна$"), ["restore-all"]),
        (rx(r"^(?:сделай )?(?:погромче|громче)$|^(?:прибавь|добавь) (?:звук|громкость)$|^увеличь громкость$"), ["volume", "up"]),
        (rx(r"^(?:сделай )?(?:потише|тише)$|^(?:убавь|убери) (?:звук|громкость)$|^уменьши громкость$"), ["volume", "down"]),
        (rx(r"^(?:выключи|отключи|включи) звук$|^без звука$|^заглуши(?: звук)?$"), ["volume", "mute"]),
        (rx(r"^(?:поставь |сделай |установи )?громкость (?:на )?(\d{1,3})(?: процентов| процента| процент)?$"),
         lambda m: ["volume", "set", str(min(100, int(m.group(1))))]),
        (rx(r"^(?:сделай )?(?:скриншот|снимок экрана)(?: экрана)?$"), ["screenshot"]),
        (rx(r"^заблокируй (?:компьютер|экран|пк)$"), ["lock"]),
        (rx(r"^(?:включи|вруби|запусти) игровой режим$"), ["game-mode", "on"]),
        (rx(r"^(?:выключи|отключи) игровой режим$"), ["game-mode", "off"]),
    ]


_RULES = _rules()
_OPEN = re.compile(r"^(?:открои|запусти|включи)\s+(.+)$")
_APPS = {normalize(a): a for a in APPS}          # в jarvis-pc уходит исходное написание («пейнт», а не «пеинт»)


def match(text: str) -> Optional[List[str]]:
    """Команда jarvis-pc для простой просьбы или None, если нужна нейросеть."""
    low = re.sub(rf"\b{_FILLER}\b", " ", normalize(text))
    low = re.sub(r"\s+", " ", low).strip()
    if not low:
        return None
    for pattern, action in _RULES:
        m = pattern.match(low)
        if m:
            return action(m) if callable(action) else list(action)
    m = _OPEN.match(low)
    if m and m.group(1) in _APPS:
        return ["open", _APPS[m.group(1)]]
    return None
